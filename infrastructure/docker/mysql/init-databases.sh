#!/bin/bash
set -eu
mysql --protocol=socket -uroot -p"${MYSQL_ROOT_PASSWORD}" <<EOSQL
CREATE DATABASE IF NOT EXISTS auth_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS application_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS docker_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS kubernetes_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS deployment_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS cicd_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS monitoring_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '${MYSQL_USER}'@'%' IDENTIFIED BY '${MYSQL_PASSWORD}';
GRANT ALL PRIVILEGES ON auth_db.* TO '${MYSQL_USER}'@'%';
GRANT ALL PRIVILEGES ON application_db.* TO '${MYSQL_USER}'@'%';
GRANT ALL PRIVILEGES ON docker_db.* TO '${MYSQL_USER}'@'%';
GRANT ALL PRIVILEGES ON kubernetes_db.* TO '${MYSQL_USER}'@'%';
GRANT ALL PRIVILEGES ON deployment_db.* TO '${MYSQL_USER}'@'%';
GRANT ALL PRIVILEGES ON cicd_db.* TO '${MYSQL_USER}'@'%';
GRANT ALL PRIVILEGES ON monitoring_db.* TO '${MYSQL_USER}'@'%';
FLUSH PRIVILEGES;
EOSQL
